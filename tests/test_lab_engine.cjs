const assert = require('node:assert/strict');
require('../lab-engine.js');
const Lab = globalThis.Linux404Lab;
let state = Lab.createState();
let r = Lab.execute(state, 'pwd');
assert.equal(r.output, '/home/usuario');
assert.equal(r.type, 'normal');
state = Lab.createState();
r = Lab.execute(state, 'ls');
assert.match(r.output, /Documentos/);
assert.match(r.output, /bienvenida\.txt/);
state = Lab.createState();
Lab.execute(state, 'cd Documentos');
r = Lab.execute(state, 'pwd');
assert.equal(r.output, '/home/usuario/Documentos');
state = Lab.createState();
Lab.execute(state, 'cd Documentos');
r = Lab.execute(state, 'mkdir PracticaLinux');
assert.equal(r.type, 'normal');
assert(!state.dirs.has('/home/usuario/PracticaLinux'));
Lab.execute(state, 'cd');
Lab.execute(state, 'mkdir PracticaLinux');
assert(state.dirs.has('/home/usuario/PracticaLinux'));
state = Lab.createState();
Lab.execute(state, 'mkdir PracticaLinux');
Lab.execute(state, 'cd PracticaLinux');
Lab.execute(state, 'touch notas.txt');
assert(state.files.has('/home/usuario/PracticaLinux/notas.txt'));
r = Lab.execute(state, 'cat notas.txt');
assert.equal(r.output, '(archivo vacío)');
state = Lab.createState();
r = Lab.execute(state, 'grep Linux bienvenida.txt');
assert.equal(r.type, 'normal');
assert.match(r.output, /Linux/);
r = Lab.execute(state, 'file bienvenida.txt');
assert.match(r.output, /texto UTF-8/);
state = Lab.createState();
Lab.execute(state, 'touch origen.txt');
r = Lab.execute(state, 'cp origen.txt copia.txt');
assert.equal(r.type, 'normal');
assert.ok(state.files.has('/home/usuario/origen.txt') && state.files.has('/home/usuario/copia.txt'));
r = Lab.execute(state, 'cp origen.txt copia.txt');
assert.equal(r.type, 'error', 'La copia no debe sobrescribir un destino');
assert.match(r.output, /No se sobrescribió/);
r = Lab.execute(state, 'mv origen.txt final.txt');
assert.equal(r.type, 'normal');
assert.ok(!state.files.has('/home/usuario/origen.txt') && state.files.has('/home/usuario/final.txt'));
for (const command of ['cp bienvenida.txt ../fuera.txt','mv bienvenida.txt sub/copia.txt','grep Linux /etc/passwd']) {
  r = Lab.execute(state, command);
  assert.equal(r.type, 'error', `Debe rechazar rutas externas: ${command}`);
}
const fileCount = state.files.size, dirCount = state.dirs.size, oldCwd = state.cwd;
r = Lab.execute(state, 'touch seguro.txt; mkdir fuera');
assert.equal(r.type, 'error');
assert.equal(state.files.size, fileCount);
assert.equal(state.dirs.size, dirCount);
r = Lab.execute(state, 'sudo rm -rf /');
assert.equal(r.type, 'error');
assert.equal(state.cwd, oldCwd);
r = Lab.execute(state, 'cd ../../etc');
assert.equal(r.type, 'error');
assert.equal(state.cwd, oldCwd);
r = Lab.execute(state, 'comando-inventado');
assert.equal(r.type, 'error');
assert.match(r.output, /No se ejecutó/);
r = Lab.execute(state, 'clear');
assert.equal(r.type, 'clear');
console.log('OK: laboratorio con copia, renombrado y consultas en memoria; sobrescritura, rutas externas y operadores rechazados.');
